// Create creates the resource and sets the initial Terraform state.
func (r *legacyNotificationChannelResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	// Retrieve values from plan.
	var plan legacyNotificationChannelResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body.
	channelPayload := &model.NotificationChannel{
		Name: plan.Name.ValueString(),
		Type: plan.Type.ValueString(),
	}

	setChannelConfigs(channelPayload, &plan)

	tflog.Debug(ctx, "Creating notification channel", map[string]any{"channel": channelPayload})

	// Create new channel.
	channel, err := r.client.CreateChannel(ctx, channelPayload)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating notification channel",
			"Could not create notification channel, unexpected error: "+err.Error(),
		)
		return
	}

	tflog.Debug(ctx, "Created notification channel", map[string]any{"channel": channel})

	// Map response to schema and populate Computed attributes.
	plan.ID = types.StringValue(channel.ID)

	// Set state to populated data.
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Read refreshes the Terraform state with the latest data.
func (r *legacyNotificationChannelResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	// Get current state.
	var state legacyNotificationChannelResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Debug(ctx, "Reading notification channel", map[string]any{"id": state.ID.ValueString()})

	// Get refreshed channel from SigNoz.
	channel, err := r.client.GetChannel(ctx, state.ID.ValueString())
	if err != nil {
		if strings.Contains(err.Error(), "404") || strings.Contains(err.Error(), "not found") {
			tflog.Warn(ctx, "Notification channel not found, removing from state", map[string]any{"id": state.ID.ValueString()})
			resp.State.RemoveResource(ctx)
			return
		}
		addErr(&resp.Diagnostics, err, operationRead, "signoz_notification_channel")
		return
	}

	// Overwrite items with refreshed state.
	state.ID = types.StringValue(channel.ID)
	state.Name = types.StringValue(channel.Name)
	state.Type = types.StringValue(channel.Type)

	setChannelStateFromAPI(channel, &state)

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Update updates the resource and sets the updated Terraform state on success.
func (r *legacyNotificationChannelResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	// Retrieve values from plan.
	var plan, state legacyNotificationChannelResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body from plan.
	channelUpdate := &model.NotificationChannel{
		ID:   state.ID.ValueString(),
		Name: plan.Name.ValueString(),
		Type: plan.Type.ValueString(),
	}

	setChannelConfigs(channelUpdate, &plan)

	tflog.Debug(ctx, "Updating notification channel", map[string]any{"channel": channelUpdate})

	// Update existing channel.
	err := r.client.UpdateChannel(ctx, state.ID.ValueString(), channelUpdate)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_notification_channel")
		return
	}

	// Preserve plan values — don't re-read from API to avoid server-side defaults
	// (html template, send_resolved) causing inconsistency errors.
	plan.ID = state.ID

	// Set refreshed state.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

