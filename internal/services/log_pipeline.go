// Create creates the resource and sets the initial Terraform state.
func (r *logPipelineResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	// Retrieve values from plan.
	var plan logPipelineResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body.
	pipelinePayload := &model.LogPipeline{
		Name:        plan.Name.ValueString(),
		Alias:       plan.Alias.ValueString(),
		Description: plan.Description.ValueString(),
		Enabled:     plan.Enabled.ValueBool(),
		OrderID:     int(plan.OrderID.ValueInt64()),
	}

	err := pipelinePayload.SetFilter(plan.Filter)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_log_pipeline")
		return
	}

	err = pipelinePayload.SetConfig(plan.Config)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_log_pipeline")
		return
	}

	tflog.Debug(ctx, "Creating log pipeline", map[string]any{"pipeline": pipelinePayload})

	// Create new log pipeline.
	pipeline, err := r.client.CreateLogPipeline(ctx, pipelinePayload)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating log pipeline",
			"Could not create log pipeline, unexpected error: "+err.Error(),
		)
		return
	}

	tflog.Debug(ctx, "Created log pipeline", map[string]any{"pipeline": pipeline})

	// Map response to schema and populate Computed attributes.
	plan.ID = types.StringValue(pipeline.ID)
	plan.Name = types.StringValue(pipeline.Name)
	plan.Alias = types.StringValue(pipeline.Alias)
	plan.Description = types.StringValue(pipeline.Description)
	plan.Enabled = types.BoolValue(pipeline.Enabled)
	plan.OrderID = types.Int64Value(int64(pipeline.OrderID))
	plan.CreatedBy = types.StringValue(pipeline.CreatedBy)
	plan.CreatedAt = types.StringValue(pipeline.CreatedAt)

	// Use the plan's filter/config to avoid extra keys from server response.
	plan.Filter, err = pipelinePayload.FilterToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_log_pipeline")
		return
	}

	plan.Config, err = pipelinePayload.ConfigToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_log_pipeline")
		return
	}

	// Set state to populated data.
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Read refreshes the Terraform state with the latest data.
func (r *logPipelineResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	// Get current state.
	var state logPipelineResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Debug(ctx, "Reading log pipeline", map[string]any{"id": state.ID.ValueString()})

	// Get refreshed pipeline from SigNoz.
	pipeline, err := r.client.GetLogPipeline(ctx, state.ID.ValueString())
	if err != nil {
		if strings.Contains(err.Error(), "404") || strings.Contains(err.Error(), "not found") {
			tflog.Warn(ctx, "Log pipeline not found, removing from state", map[string]any{"id": state.ID.ValueString()})
			resp.State.RemoveResource(ctx)
			return
		}
		addErr(&resp.Diagnostics, err, operationRead, "signoz_log_pipeline")
		return
	}

	// Overwrite items with refreshed state.
	state.ID = types.StringValue(pipeline.ID)
	state.Name = types.StringValue(pipeline.Name)
	state.Alias = types.StringValue(pipeline.Alias)
	state.Description = types.StringValue(pipeline.Description)
	state.Enabled = types.BoolValue(pipeline.Enabled)
	state.OrderID = types.Int64Value(int64(pipeline.OrderID))
	state.CreatedBy = types.StringValue(pipeline.CreatedBy)
	state.CreatedAt = types.StringValue(pipeline.CreatedAt)

	state.Filter, err = pipeline.FilterToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationRead, "signoz_log_pipeline")
		return
	}

	state.Config, err = pipeline.ConfigToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationRead, "signoz_log_pipeline")
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Update updates the resource and sets the updated Terraform state on success.
func (r *logPipelineResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	// Retrieve values from plan.
	var plan, state logPipelineResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body from plan.
	pipelineUpdate := &model.LogPipeline{
		ID:          state.ID.ValueString(),
		Name:        plan.Name.ValueString(),
		Alias:       plan.Alias.ValueString(),
		Description: plan.Description.ValueString(),
		Enabled:     plan.Enabled.ValueBool(),
		OrderID:     int(plan.OrderID.ValueInt64()),
		CreatedBy:   state.CreatedBy.ValueString(),
		CreatedAt:   state.CreatedAt.ValueString(),
	}

	err := pipelineUpdate.SetFilter(plan.Filter)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_log_pipeline")
		return
	}

	err = pipelineUpdate.SetConfig(plan.Config)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_log_pipeline")
		return
	}

	tflog.Debug(ctx, "Updating log pipeline", map[string]any{"pipeline": pipelineUpdate})

	// Update existing log pipeline.
	pipeline, err := r.client.UpdateLogPipeline(ctx, state.ID.ValueString(), pipelineUpdate)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_log_pipeline")
		return
	}

	// Overwrite items with refreshed state.
	plan.ID = types.StringValue(pipeline.ID)
	plan.Name = types.StringValue(pipeline.Name)
	plan.Alias = types.StringValue(pipeline.Alias)
	plan.Description = types.StringValue(pipeline.Description)
	plan.Enabled = types.BoolValue(pipeline.Enabled)
	plan.OrderID = types.Int64Value(int64(pipeline.OrderID))
	plan.CreatedBy = types.StringValue(pipeline.CreatedBy)
	plan.CreatedAt = types.StringValue(pipeline.CreatedAt)

	// Use the plan's filter/config to avoid extra keys from server response.
	plan.Filter, err = pipelineUpdate.FilterToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_log_pipeline")
		return
	}

	plan.Config, err = pipelineUpdate.ConfigToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_log_pipeline")
		return
	}

	// Set refreshed state.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

