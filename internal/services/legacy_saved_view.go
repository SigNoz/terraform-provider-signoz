// legacySavedViewResource is the resource implementation.
type legacySavedViewResource struct {
	client *legacyclient.Client
}

// legacySavedViewResourceModel maps the resource schema data.
type legacySavedViewResourceModel struct {
	UUID         types.String `tfsdk:"uuid"`
	Name         types.String `tfsdk:"name"`
	Category     types.String `tfsdk:"category"`
	SourcePage   types.String `tfsdk:"source_page"`
	ExplorerData types.String `tfsdk:"explorer_data"`
	ExtraData    types.String `tfsdk:"extra_data"`
	Tags         types.List   `tfsdk:"tags"`
	CreatedAt    types.String `tfsdk:"created_at"`
	CreatedBy    types.String `tfsdk:"created_by"`
	UpdatedAt    types.String `tfsdk:"updated_at"`
}

// Configure adds the provider configured client to the resource.
func (r *legacySavedViewResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	api, ok := req.ProviderData.(*apiclients.WrappedClient)
	if !ok {
		addErr(
			&resp.Diagnostics,
			fmt.Errorf("unexpected data source configure type. Expected *apiclients.WrappedClient, got: %T. "+
				"Please report this issue to the provider developers", req.ProviderData),
			operationConfigure, "signoz_saved_view",
		)

		return
	}

	legacyClient, err := legacyclient.NewClient(api)
	if err != nil {
		resp.Diagnostics.AddError("Unable to build legacy SigNoz client", err.Error())
		return
	}

	r.client = legacyClient
}

// Metadata returns the resource type name.
func (r *legacySavedViewResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = "signoz_saved_view"
}

// Schema defines the schema for the resource.
func (r *legacySavedViewResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Creates and manages saved view resources in SigNoz.",
		Attributes: map[string]schema.Attribute{
			attr.ViewName: schema.StringAttribute{
				Required:    true,
				Description: "Name of the saved view.",
			},
			attr.SourcePage: schema.StringAttribute{
				Required:    true,
				Description: "Source page of the saved view. Possible values are: logs, traces, and metrics.",
				Validators: []validator.String{
					stringvalidator.OneOf("logs", "traces", "metrics"),
				},
			},
			attr.ExplorerData: schema.StringAttribute{
				Required:    true,
				Description: "Explorer data of the saved view as a JSON string.",
			},
			attr.ViewTags: schema.ListAttribute{
				Optional:    true,
				Computed:    true,
				ElementType: types.StringType,
				Description: "Tags associated with the saved view.",
			},
			attr.Category: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Category of the saved view.",
			},
			attr.ExtraData: schema.StringAttribute{
				Optional:    true,
				Computed:    true,
				Description: "Extra data associated with the saved view.",
			},
			// Computed attributes.
			attr.UUID: schema.StringAttribute{
				Computed:    true,
				Description: "Autogenerated unique UUID for the saved view.",
			},
			attr.CreatedAt: schema.StringAttribute{
				Computed:    true,
				Description: "Creation time of the saved view.",
			},
			attr.CreatedBy: schema.StringAttribute{
				Computed:    true,
				Description: "Creator of the saved view.",
			},
			attr.UpdatedAt: schema.StringAttribute{
				Computed:    true,
				Description: "Last update time of the saved view.",
			},
		},
	}
}

// Create creates the resource and sets the initial Terraform state.
func (r *legacySavedViewResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	// Retrieve values from plan.
	var plan legacySavedViewResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body.
	payload := &model.SavedView{
		Name:       plan.Name.ValueString(),
		SourcePage: plan.SourcePage.ValueString(),
		Category:   plan.Category.ValueString(),
		ExtraData:  plan.ExtraData.ValueString(),
	}

	err := payload.SetExplorerData(plan.ExplorerData)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_saved_view")
		return
	}

	if !plan.Tags.IsNull() && !plan.Tags.IsUnknown() {
		payload.SetTags(plan.Tags)
	}

	tflog.Debug(ctx, "Creating saved view", map[string]any{"savedView": payload})

	// Create new saved view.
	savedView, err := r.client.CreateSavedView(ctx, payload)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating saved view",
			"Could not create saved view, unexpected error: "+err.Error(),
		)
		return
	}

	tflog.Debug(ctx, "Created saved view", map[string]any{"savedView": savedView})

	// Map response to schema and populate Computed attributes.
	plan.UUID = types.StringValue(savedView.UUID)
	plan.CreatedAt = types.StringValue(savedView.CreatedAt)
	plan.CreatedBy = types.StringValue(savedView.CreatedBy)
	plan.UpdatedAt = types.StringValue(savedView.UpdatedAt)
	plan.Category = types.StringValue(savedView.Category)
	plan.ExtraData = types.StringValue(savedView.ExtraData)

	// Use the payload's explorer data to avoid extra keys from the response.
	plan.ExplorerData, err = payload.ExplorerDataToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationCreate, "signoz_saved_view")
		return
	}

	var diagTags diag.Diagnostics
	plan.Tags, diagTags = savedView.TagsToTerraform()
	resp.Diagnostics.Append(diagTags...)

	// Set state to populated data.
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Read refreshes the Terraform state with the latest data.
func (r *legacySavedViewResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	// Get current state.
	var state legacySavedViewResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Debug(ctx, "Reading saved view", map[string]any{"uuid": state.UUID.ValueString()})

	// Get refreshed saved view from SigNoz.
	savedView, err := r.client.GetSavedView(ctx, state.UUID.ValueString())
	if err != nil {
		if strings.Contains(err.Error(), "404") || strings.Contains(err.Error(), "not found") {
			tflog.Warn(ctx, "Saved view not found, removing from state", map[string]any{"uuid": state.UUID.ValueString()})
			resp.State.RemoveResource(ctx)
			return
		}
		addErr(&resp.Diagnostics, err, operationRead, "signoz_saved_view")
		return
	}

	// Overwrite items with refreshed state.
	state.Name = types.StringValue(savedView.Name)
	state.SourcePage = types.StringValue(savedView.SourcePage)
	state.Category = types.StringValue(savedView.Category)
	state.ExtraData = types.StringValue(savedView.ExtraData)
	state.CreatedAt = types.StringValue(savedView.CreatedAt)
	state.CreatedBy = types.StringValue(savedView.CreatedBy)
	state.UpdatedAt = types.StringValue(savedView.UpdatedAt)

	state.ExplorerData, err = savedView.ExplorerDataToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationRead, "signoz_saved_view")
		return
	}

	var diagTags diag.Diagnostics
	state.Tags, diagTags = savedView.TagsToTerraform()
	resp.Diagnostics.Append(diagTags...)

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

// Update updates the resource and sets the updated Terraform state on success.
func (r *legacySavedViewResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	// Retrieve values from plan.
	var plan, state legacySavedViewResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Generate API request body from plan.
	payload := &model.SavedView{
		UUID:       state.UUID.ValueString(),
		Name:       plan.Name.ValueString(),
		SourcePage: plan.SourcePage.ValueString(),
		Category:   plan.Category.ValueString(),
		ExtraData:  plan.ExtraData.ValueString(),
		CreatedAt:  state.CreatedAt.ValueString(),
		CreatedBy:  state.CreatedBy.ValueString(),
		UpdatedAt:  state.UpdatedAt.ValueString(),
	}

	err := payload.SetExplorerData(plan.ExplorerData)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_saved_view")
		return
	}

	if !plan.Tags.IsNull() && !plan.Tags.IsUnknown() {
		payload.SetTags(plan.Tags)
	}

	tflog.Debug(ctx, "Updating saved view", map[string]any{"savedView": payload})

	// Update existing saved view.
	err = r.client.UpdateSavedView(ctx, state.UUID.ValueString(), payload)
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_saved_view")
		return
	}

	// Fetch updated saved view.
	savedView, err := r.client.GetSavedView(ctx, state.UUID.ValueString())
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_saved_view")
		return
	}

	// Overwrite items with refreshed state.
	plan.UUID = types.StringValue(savedView.UUID)
	plan.Name = types.StringValue(savedView.Name)
	plan.SourcePage = types.StringValue(savedView.SourcePage)
	plan.Category = types.StringValue(savedView.Category)
	plan.ExtraData = types.StringValue(savedView.ExtraData)
	plan.CreatedAt = types.StringValue(savedView.CreatedAt)
	plan.CreatedBy = types.StringValue(savedView.CreatedBy)
	plan.UpdatedAt = types.StringValue(savedView.UpdatedAt)

	// Use the payload's explorer data to avoid extra keys from the response.
	plan.ExplorerData, err = payload.ExplorerDataToTerraform()
	if err != nil {
		addErr(&resp.Diagnostics, err, operationUpdate, "signoz_saved_view")
		return
	}

	var diagTags diag.Diagnostics
	plan.Tags, diagTags = savedView.TagsToTerraform()
	resp.Diagnostics.Append(diagTags...)

	// Set refreshed state.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
}

